import subprocess
import os

def get_git_version():
    try:

        # Get our directory, which is the directory that contains all the firmware
        script_dir = os.path.dirname(os.path.abspath(__file__)) 
        
        # get the repository root
        repo_root = subprocess.check_output(['git', 'rev-parse', '--show-toplevel'], cwd=script_dir).strip().decode('utf-8')    
        
        # Get the firmware directory relative to the repository root
        rel_path = os.path.relpath(script_dir, repo_root)   

        # Create a git command that gets the hash of the most recent commit that modified the firmware directory 
        commit_cmd = ['git', '-C', repo_root, 'log', '-n', '1', '--pretty=format:%h', '--', rel_path]  
        
        # Execute the command
        commit_hash = subprocess.check_output(commit_cmd).strip().decode('utf-8')   
        
        # Create a command that checks for uncommitted changes (i.e. the repository is dirty)
        status_cmd = ['git', '-C', repo_root, 'status', '--porcelain', '-uno', '--', rel_path]
        
        # Execute the command
        status_output = subprocess.check_output(status_cmd).strip().decode('utf-8')
        
        
        if len(status_output) > 0:
            return f"{commit_hash}-dirty"
        return commit_hash

    except Exception as e:
        return f"unknown_err_{str(e)[:10]}"

version = get_git_version()

version_contents = f"""/* This file is automatically generated during building. Don't edit it.*/
#ifndef VERSION_H
#define VERSION_H

#define FIRMWARE_VERSION "{version}"

#endif
"""

script_dir = os.path.dirname(os.path.abspath(__file__))

version_path = os.path.join(script_dir, "source\\version.h")

with open(version_path, "w") as f:
    f.write(version_contents)
print(f"Updated version.h: {version}")